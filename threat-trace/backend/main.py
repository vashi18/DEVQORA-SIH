# API: ANALYZE .EML FILE
# ============================================================

@app.post("/api/analyze/file")
async def analyze_email_file(
    file: UploadFile = File(...)
):

    if not file.filename:
        raise HTTPException(
            status_code=400,
            detail="Filename is missing."
        )

    if not file.filename.lower().endswith(".eml"):
        raise HTTPException(
            status_code=400,
            detail="Only .eml files are supported."
        )

    content = await file.read()

    if not content:
        raise HTTPException(
            status_code=400,
            detail="Uploaded file is empty."
        )

    if len(content) > MAX_EMAIL_SIZE:
        raise HTTPException(
            status_code=413,
            detail="Email exceeds the 2 MB size limit."
        )

    try:
        raw_email = content.decode(
            "utf-8",
            errors="replace"
        )

    except Exception as error:

        raise HTTPException(
            status_code=400,
            detail=f"Unable to decode email file: {error}"
        )

    try:
        result = analyze_raw_email(
            raw_email
        )

        return result

    except Exception as error:

        print("\n========== FILE ANALYSIS ERROR ==========")
        print(type(error).__name__)
        print(str(error))
        print("=========================================\n")

        raise HTTPException(
            status_code=500,
            detail=f"Email file analysis failed: {str(error)}"
        )


