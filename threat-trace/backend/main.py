def analyze_raw_email(raw_email: str) -> dict:

    # --------------------------------------------------------
    # 1. Parse RFC 822 email
    # --------------------------------------------------------

    parsed_email = parse_email(raw_email)

    # --------------------------------------------------------
    # 2. SPF / DKIM / DMARC
    # --------------------------------------------------------

    auth_data = analyze_authentication(parsed_email)

    # --------------------------------------------------------
    # 3. Received header / originating IP
    # --------------------------------------------------------

    ip_data = analyze_received_chain(
        parsed_email.get("received", [])
    )

    origin_summary = build_origin_summary(ip_data)

    originating_ip = ip_data.get("originating_ip")

    # --------------------------------------------------------
    # 4. IP Geolocation
    # --------------------------------------------------------

    geo_data = get_geolocation(originating_ip)

    # --------------------------------------------------------
    # 5. URL intelligence
    # --------------------------------------------------------

    url_data = analyze_email_urls(
        parsed_email.get("body", ""),
        auth_data.get("from_domain", ""),
    )

    # --------------------------------------------------------
    # 6. Deterministic forensic evidence
    # --------------------------------------------------------

    evidence_data = calculate_evidence(
        parsed_email,
        auth_data,
        ip_data,
        url_data,
    )

    # --------------------------------------------------------
    # 7. Risk calculation
    # --------------------------------------------------------

    threat_score = evidence_data.get(
        "threat_score",
        0
    )

    risk_data = calculate_risk(threat_score)

    # --------------------------------------------------------
    # 8. Confidence
    # --------------------------------------------------------

    evidence_list = evidence_data.get(
        "evidence",
        []
    )

    confidence_data = calculate_confidence(
        threat_score,
        evidence_list,
        auth_data,
        url_data,
        ip_data,
    )

    # --------------------------------------------------------
    # 9. Explainability
    # --------------------------------------------------------

    classification = evidence_data.get(
        "classification",
        "legitimate"
    )

    explanation_data = build_explanation(
        threat_score,
        classification,
        evidence_list,
        risk_data.get("risk_level", "LOW"),
    )

    # --------------------------------------------------------
    # 10. AI ANALYSIS
    # --------------------------------------------------------

    # Send the normalized forensic information to ai_manager.
    #
    # ai_manager decides:
    #
    # Gemini
    #   ↓
    # Groq
    #   ↓
    # OpenRouter
    #   ↓
    # Ollama
    #
    # depending on your configuration.

    ai_input = {
        "from": parsed_email.get("from", ""),
        "to": parsed_email.get("to", ""),
        "subject": parsed_email.get("subject", ""),
        "date": parsed_email.get("date", ""),
        "body": parsed_email.get("body", ""),

        "received": parsed_email.get(
            "received",
            []
        ),

        "spf": auth_data.get(
            "spf",
            ""
        ),

        "dkim": auth_data.get(
            "dkim",
            ""
        ),

        "dmarc": auth_data.get(
            "dmarc",
            ""
        ),

        "originating_ip": originating_ip or "",

        "url_count": url_data.get(
            "url_count",
            0
        ),

        "suspicious_url_count": url_data.get(
            "suspicious_url_count",
            0
        ),

        "deterministic_threat_score": threat_score,

        "deterministic_classification": classification,

        "forensic_evidence": evidence_list,
    }

    try:
        ai_data = analyze_email_with_ai(ai_input)

    except Exception as error:
        # AI must NEVER crash the entire forensic API.
        ai_data = {
            "threat_score": threat_score,
            "classification": classification,
            "psychological_tactic": "",
            "forensic_summary": (
                "AI analysis failed. "
                "Deterministic forensic analysis was used."
            ),
            "indicators_of_compromise": [],
            "ai_provider": "none",
            "ai_status": "failed",
            "ai_error": str(error),
        }

    # --------------------------------------------------------
    # 11. Decide final classification
    # --------------------------------------------------------

    # Deterministic engine remains the safety net.
    #
    # If AI returns a valid result, we expose both:
    #
    # deterministic result
    # AI result
    #
    # This is useful during SIH demonstration.

    final_score = ai_data.get(
        "threat_score",
        threat_score
    )

    final_classification = ai_data.get(
        "classification",
        classification
    )

    # Ensure valid score
    try:
        final_score = int(final_score)
    except Exception:
        final_score = threat_score

    final_score = max(
        0,
        min(100, final_score)
    )

    allowed_classes = {
        "legitimate",
        "phishing",
        "bec",
        "spoofed",
    }

    if final_classification not in allowed_classes:
        final_classification = classification

    # --------------------------------------------------------
    # 12. Final risk based on AI score
    # --------------------------------------------------------

    final_risk = calculate_risk(
        final_score
    )

    # --------------------------------------------------------
    # 13. Case + evidence hashes
    # --------------------------------------------------------

    evidence_for_case = {
        "parsed_email": parsed_email,
        "authentication": auth_data,
        "origin": ip_data,
        "geolocation": geo_data,
        "urls": url_data,
        "evidence": evidence_data,
        "risk": final_risk,
        "confidence": confidence_data,
        "explanation": explanation_data,
        "ai_analysis": ai_data,
    }

    case_data = create_case(
        raw_email,
        evidence_for_case
    )

    case_id = case_data["case_id"]

    # --------------------------------------------------------
    # 14. Generate forensic PDF
    # --------------------------------------------------------

    analysis_for_report = {
        "case_id": case_id,
        "created_at": case_data.get(
            "created_at",
            datetime.now(timezone.utc).isoformat()
        ),

        "threat_score": final_score,
        "risk_level": final_risk.get(
            "risk_level",
            "LOW"
        ),

        "classification": final_classification,

        "sender": parsed_email.get(
            "from",
            ""
        ),

        "recipient": parsed_email.get(
            "to",
            ""
        ),

        "subject": parsed_email.get(
            "subject",
            ""
        ),

        "date": parsed_email.get(
            "date",
            ""
        ),

        "spf": auth_data.get(
            "spf",
            ""
        ),

        "dkim": auth_data.get(
            "dkim",
            ""
        ),

        "dmarc": auth_data.get(
            "dmarc",
            ""
        ),

        "originating_ip": originating_ip,

        "origin_confidence": ip_data.get(
            "origin_confidence",
            ""
        ),

        "country": geo_data.get(
            "country"
        ),

        "region": geo_data.get(
            "region"
        ),

        "city": geo_data.get(
            "city"
        ),

        "latitude": geo_data.get(
            "latitude"
        ),

        "longitude": geo_data.get(
            "longitude"
        ),

        "isp": geo_data.get(
            "isp"
        ),

        "url_data": url_data,

        "indicators_of_compromise": ai_data.get(
            "indicators_of_compromise",
            []
        ),

        "evidence": evidence_list,

        "explanation": explanation_data,

        "confidence": confidence_data,

        "ai_analysis": ai_data,

        "evidence_integrity": case_data.get(
            "evidence_integrity",
            {}
        ),
    }

    report_path = REPORTS_DIR / f"{case_id}.pdf"

    try:
        generate_forensic_report(
            analysis_for_report,
            str(report_path)
        )
    except Exception as error:
        # Report failure should not destroy the analysis.
        report_path = None
        report_error = str(error)
    else:
        report_error = None

    # --------------------------------------------------------
    # 15. Save original email
    # --------------------------------------------------------

    if final_classification == "legitimate":
        email_directory = ACTUAL_DIR
    else:
        email_directory = SPAM_DIR

    filename = f"{case_id}.eml"

    email_path = email_directory / filename

    try:
        email_path.write_text(
            raw_email,
            encoding="utf-8"
        )
    except Exception as error:
        email_path = None
        email_save_error = str(error)
    else:
        email_save_error = None

    # --------------------------------------------------------
    # 16. Final API response
    # --------------------------------------------------------

    response = {
        # ====================================================
        # CASE
        # ====================================================

        "case": {
            "case_id": case_id,

            "created_at": case_data.get(
                "created_at"
            ),

            "email_file": (
                str(email_path)
                if email_path
                else None
            ),

            "report_file": (
                str(report_path)
                if report_path
                else None
            ),
        },

        # ====================================================
        # FINAL RESULT
        # ====================================================

        "result": {
            "threat_score": final_score,

            "risk_level": final_risk.get(
                "risk_level"
            ),

            "classification": final_classification,

            "recommended_action": final_risk.get(
                "recommended_action"
            ),
        },

        # ====================================================
        # EMAIL
        # ====================================================

        "email": {
            "from": parsed_email.get(
                "from",
                ""
            ),

            "to": parsed_email.get(
                "to",
                ""
            ),

            "subject": parsed_email.get(
                "subject",
                ""
            ),

            "date": parsed_email.get(
                "date",
                ""
            ),
        },

        # ====================================================
        # AUTHENTICATION
        # ====================================================

        "authentication": {
            "spf": auth_data.get(
                "spf",
                "unknown"
            ),

            "dkim": auth_data.get(
                "dkim",
                "unknown"
            ),

            "dmarc": auth_data.get(
                "dmarc",
                "unknown"
            ),

            "risk": auth_data.get(
                "authentication_risk",
                0
            ),

            "findings": auth_data.get(
                "findings",
                []
            ),
        },

        # ====================================================
        # ORIGIN
        # ====================================================

        "origin": {
            "originating_ip": originating_ip,

            "confidence": ip_data.get(
                "origin_confidence"
            ),

            "method": ip_data.get(
                "origin_method"
            ),

            "header_count": ip_data.get(
                "header_count",
                0
            ),

            "public_ip_count": len(
                ip_data.get(
                    "public_ips",
                    []
                )
            ),

            "summary": origin_summary,
        },

        # ====================================================
        # GEOLOCATION
        # ====================================================

        "geolocation": geo_data,

        # ====================================================
        # URL INTELLIGENCE
        # ====================================================

        "url_intelligence": url_data,

        # ====================================================
        # DETERMINISTIC FORENSICS
        # ====================================================

        "forensics": {
            "threat_score": threat_score,

            "classification": classification,

            "evidence": evidence_list,

            "evidence_details": evidence_data.get(
                "evidence_details",
                []
            ),

            "risk_breakdown": evidence_data.get(
                "risk_breakdown",
                {}
            ),

            "details": evidence_data.get(
                "details",
                {}
            ),
        },

        # ====================================================
        # CONFIDENCE
        # ====================================================

        "confidence": confidence_data,

        # ====================================================
        # EXPLAINABILITY
        # ====================================================

        "explanation": explanation_data,

        # ====================================================
        # AI
        # ====================================================

        "ai_analysis": ai_data,

        # ====================================================
        # INTEGRITY
        # ====================================================

        "evidence_integrity": case_data.get(
            "evidence_integrity",
            {}
        ),

        # ====================================================
        # ERRORS / WARNINGS
        # ====================================================

        "warnings": {
            "report_error": report_error,

            "email_save_error": email_save_error,
        },
    }

    return response


