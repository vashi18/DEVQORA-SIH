def get_raw_email(request: EmailRequest) -> str:
    raw_email = request.email or request.raw_email

    if not raw_email:
        raise HTTPException(
            status_code=400,
            detail="No email content supplied."
        )

    if not raw_email.strip():
        raise HTTPException(
            status_code=400,
            detail="Email content is empty."
        )

    if len(raw_email.encode("utf-8", errors="replace")) > MAX_EMAIL_SIZE:
        raise HTTPException(
            status_code=413,
            detail="Email exceeds the 2 MB size limit."
        )

    return raw_email


def safe_filename(filename: str) -> str:
    """
    Prevent unsafe filenames from being used on disk.
    """
    filename = Path(filename).name
    filename = re.sub(r"[^a-zA-Z0-9._-]", "_", filename)

    if not filename:
        filename = "email.eml"

    return filename


def unique_email_path(directory: Path, filename: str) -> Path:
    filename = safe_filename(filename)

    path = directory / filename

    if not path.exists():
        return path

    stem = path.stem
    suffix = path.suffix

    return directory / f"{stem}_{uuid.uuid4().hex[:8]}{suffix}"


def safe_case_id(case_id: str) -> str:
    """
    Only allow the case ID format generated by case_manager.py.
    """
    pattern = r"^TT-\d{8}-[A-Fa-f0-9]{8}$"

    if not re.fullmatch(pattern, case_id):
        raise HTTPException(
            status_code=400,
            detail="Invalid case ID format."
        )

    return case_id


