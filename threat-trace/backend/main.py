@app.get("/api/reports/{case_id}")
async def get_report(case_id: str):

    case_id = safe_case_id(case_id)

    report_path = REPORTS_DIR / f"{case_id}.pdf"

    if not report_path.exists():
        raise HTTPException(
            status_code=404,
            detail="Forensic report not found."
        )

    return FileResponse(
        path=str(report_path),
        media_type="application/pdf",
        filename=f"{case_id}.pdf",
    )


